CREATE TABLE repayment_plan_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    version BIGINT NOT NULL CHECK (version > 1),
    effective_date DATE NOT NULL,
    input_data_revision BIGINT NOT NULL CHECK (input_data_revision >= 0),
    mode TEXT NOT NULL CHECK (mode IN ('MATURITY','PREFERENCE','TARGET_DATE','EXTRA_AMOUNT','MONTHLY_AMOUNT','STRATEGY')),
    preference TEXT CHECK (preference IN ('FAST','BALANCED','STABLE')),
    target_date DATE,
    target_payoff_date DATE,
    monthly_extra_cash BIGINT NOT NULL CHECK (monthly_extra_cash >= 0),
    monthly_saving BIGINT NOT NULL CHECK (monthly_saving >= 0),
    requested_extra_monthly_payment BIGINT CHECK (requested_extra_monthly_payment >= 0),
    requested_monthly_amount BIGINT CHECK (requested_monthly_amount >= 0),
    requested_saving_amount BIGINT CHECK (requested_saving_amount >= 0),
    plan_start_principal BIGINT NOT NULL CHECK (plan_start_principal >= 0),
    terms_snapshot JSONB NOT NULL CHECK (jsonb_typeof(terms_snapshot)='object'),
    source_report_id BIGINT CHECK (source_report_id > 0),
    source_strategy_version TEXT,
    source_strategy_code TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id),
    UNIQUE(user_id,loan_id,version),
    CHECK ((mode='PREFERENCE' AND preference IS NOT NULL) OR (mode<>'PREFERENCE' AND preference IS NULL)),
    CHECK (mode<>'TARGET_DATE' OR target_date IS NOT NULL),
    CHECK (mode<>'EXTRA_AMOUNT' OR requested_extra_monthly_payment IS NOT NULL),
    CHECK (mode<>'MONTHLY_AMOUNT' OR requested_monthly_amount IS NOT NULL),
    CHECK ((mode='STRATEGY' AND source_report_id IS NOT NULL AND length(trim(source_strategy_version))>0 AND length(trim(source_strategy_code))>0
            AND source_strategy_version IS NOT NULL AND source_strategy_code IS NOT NULL)
        OR (mode<>'STRATEGY' AND source_report_id IS NULL AND source_strategy_version IS NULL AND source_strategy_code IS NULL)),
    CHECK (target_date IS NULL OR target_date >= effective_date),
    CHECK (target_payoff_date IS NULL OR target_payoff_date >= effective_date),
    CHECK (terms_snapshot ?& ARRAY['loan_id','user_id','outstanding','method','maturity_date','snapshot_date','status']),
    CHECK ((terms_snapshot->>'loan_id') IS NOT NULL AND (terms_snapshot->>'user_id') IS NOT NULL
        AND (terms_snapshot->>'outstanding') IS NOT NULL AND (terms_snapshot->>'method') IS NOT NULL
        AND (terms_snapshot->>'maturity_date') IS NOT NULL AND (terms_snapshot->>'snapshot_date') IS NOT NULL
        AND (terms_snapshot->>'status') IS NOT NULL),
    CHECK ((terms_snapshot->>'loan_id')::bigint=loan_id AND (terms_snapshot->>'user_id')::bigint=user_id
        AND (terms_snapshot->>'outstanding')::bigint=plan_start_principal AND terms_snapshot->>'status'='ACTIVE'),
    CHECK (effective_date BETWEEN (terms_snapshot->>'snapshot_date')::date AND (terms_snapshot->>'maturity_date')::date),
    CHECK (target_date IS NULL OR target_date <= (terms_snapshot->>'maturity_date')::date),
    CHECK (target_payoff_date IS NULL OR target_payoff_date <= (terms_snapshot->>'maturity_date')::date),
    CHECK ((terms_snapshot->>'method'='BULLET' AND monthly_extra_cash=0)
        OR (terms_snapshot->>'method' IN ('EQUAL_PAYMENT','EQUAL_PRINCIPAL','GRACE_INSTALLMENT') AND monthly_saving=0))
);
CREATE INDEX repayment_plan_versions_date_idx ON repayment_plan_versions(user_id,loan_id,effective_date,version);

CREATE FUNCTION reject_repayment_plan_version_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'repayment plan versions are append-only';
END;
$$;
CREATE TRIGGER repayment_plan_versions_immutable BEFORE UPDATE OR DELETE ON repayment_plan_versions
    FOR EACH ROW EXECUTE FUNCTION reject_repayment_plan_version_mutation();
