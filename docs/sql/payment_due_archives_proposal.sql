CREATE TABLE payment_due_archives (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES demo_users(id),
 loan_id BIGINT NOT NULL,
 due_date DATE NOT NULL,
 due_snapshot JSONB NOT NULL CHECK(jsonb_typeof(due_snapshot)='object'),
 archived_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id)
);
CREATE INDEX payment_due_archives_scope_idx ON payment_due_archives(user_id,loan_id,due_date,id DESC);
