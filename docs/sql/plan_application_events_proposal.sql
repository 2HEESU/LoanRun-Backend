CREATE TABLE plan_application_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES demo_users(id),
 input_revision BIGINT NOT NULL CHECK(input_revision>=0),
 overall_exists BOOLEAN NOT NULL,
 strategy_code TEXT NOT NULL,
 allocations JSONB NOT NULL CHECK(jsonb_typeof(allocations)='array'),
 applied_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX plan_application_events_owner_idx ON plan_application_events(user_id,id DESC);
