CREATE TABLE comparison_settings (
    user_id BIGINT PRIMARY KEY REFERENCES demo_users(id),
    consented BOOLEAN NOT NULL DEFAULT FALSE,
    age_group VARCHAR(16) CHECK (age_group IN ('AGE_20S','AGE_30S','AGE_40S','AGE_50_PLUS')),
    income_decile INTEGER CHECK (income_decile BETWEEN 1 AND 5),
    CHECK (NOT consented OR (age_group IS NOT NULL AND income_decile IS NOT NULL))
);
CREATE TABLE report_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    loan_id BIGINT CHECK (loan_id > 0),
    scope_key VARCHAR(32) NOT NULL,
    data_revision BIGINT NOT NULL CHECK (data_revision >= 0),
    basis_month DATE NOT NULL CHECK (EXTRACT(DAY FROM basis_month)=1),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
    input_payload TEXT NOT NULL,
    result_payload TEXT,
    strategy_payload TEXT,
    error_code VARCHAR(64),
    explanation_source VARCHAR(16),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    generated_at TIMESTAMP WITH TIME ZONE,
    next_retry_at TIMESTAMP WITH TIME ZONE,
    UNIQUE(user_id,scope_key,data_revision,basis_month)
);
CREATE INDEX report_jobs_user_scope_idx ON report_jobs(user_id,scope_key,id DESC);
CREATE TABLE report_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    attempted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX report_attempts_user_time_idx ON report_attempts(user_id,attempted_at);
CREATE TABLE strategy_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES report_jobs(id),
    strategy_version VARCHAR(100) NOT NULL,
    code VARCHAR(32) NOT NULL,
    strategy_type VARCHAR(32) NOT NULL,
    data_revision BIGINT NOT NULL CHECK (data_revision >= 0),
    computed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    allocations_payload TEXT NOT NULL,
    simulation_payload TEXT NOT NULL,
    feasible BOOLEAN NOT NULL,
    UNIQUE(report_id,strategy_version,code)
);
