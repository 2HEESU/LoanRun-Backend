CREATE TABLE demo_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_digest VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL DEFAULT '사용자',
    occupation VARCHAR(50),
    income_type VARCHAR(16),
    onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE,
    plan_type VARCHAR(8) NOT NULL DEFAULT 'FREE',
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_demo_user_income CHECK (income_type IN ('REGULAR', 'IRREGULAR')),
    CONSTRAINT ck_demo_user_plan CHECK (plan_type IN ('FREE', 'PRO'))
);

-- Spring Session JDBC PostgreSQL schema (Spring Session 3.x).
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    http_method VARCHAR(8) NOT NULL,
    request_path VARCHAR(300) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    body_hash VARCHAR(64) NOT NULL,
    response_status INTEGER NOT NULL,
    response_body TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (user_id, http_method, request_path, request_key)
);

-- Per-user default display preferences belong to the bootstrap user lifecycle.
CREATE TABLE notification_settings (
    user_id BIGINT PRIMARY KEY REFERENCES demo_users(id),
    payment_due BOOLEAN NOT NULL DEFAULT TRUE,
    report_update BOOLEAN NOT NULL DEFAULT TRUE,
    rate_reset BOOLEAN NOT NULL DEFAULT TRUE,
    grace_end BOOLEAN NOT NULL DEFAULT TRUE
);
